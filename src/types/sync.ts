/**
 * Sync types — interfaces for SyncService server payloads and action queue.
 *
 * These replace raw `any` casts in SyncService.ts while accepting that
 * WatermelonDB prepareUpdate callbacks inherently require `any`.
 */

import { TaskOrigin } from './index';

/** Payload for action queue items */
export interface ActionPayload {
  taskId?: string;
  task_id?: string;
  id?: string;
  fulfilledRole?: string;
  requestId?: string;
  text?: string;
  attachments?: Array<{ uri: string; name: string; type: string }>;
  comment?: string;
  data?: Record<string, unknown>;
  expiresAt?: number;
}

/** Server task assignment DTO (from GET /tasks/:requestId) */
export interface ServerTaskAssignment {
  id: string;
  taskId: string;
  userId: string;
  user?: { id: string; fullName: string; email: string };
  userName?: string;
  fulfilledRole?: string;
  status: string;
  assignedAt: string;
  completedAt?: string;
}

/** Server task DTO */
export interface ServerTask {
  id: string;
  title: string;
  description?: string;
  status: string;
  neededPeopleCount?: number;
  requiredRoles?: string[];
  priority?: number;
  origin?: TaskOrigin | null;
  createdByUserId?: string | null;
  isAutoGenerated?: boolean;
  deadline?: string;
  chatId?: string;
  assignments?: ServerTaskAssignment[];
  createdAt?: string;
}

/** Server request DTO */
export interface ServerRequest {
  id: string;
  title: string;
  description?: string;
  category: string;
  urgency: string;
  status: string;
  requiredClearance?: string;
  creatorId?: string | null;
  creatorName?: string | null;
  managingOrganizationId?: string | null;
  cancelledByUserId?: string | null;
  cancelledAt?: string | null;
  cancelReason?: string | null;
  latitude?: number | null;
  longitude?: number | null;
  isLocationHidden?: boolean;
  tags?: string[];
  additionalInfo?: Array<{ id: string; text: string; attachments: any[]; createdAt: string }>;
  mediaUrls?: Array<{ url: string; name: string; type: string }>;
  reportUrls?: string[];
  deadline?: string;
  fundraisingUrl?: string;
  createdAt?: string;
}

/** Sync event types for listeners */
export interface SyncEvent {
  type: 'sync_success' | 'sync_error' | 'last_sync' | 'sync_conflict' | 'queue_failed';
  title: string;
  description: string;
  metadata?: Record<string, unknown>;
}
